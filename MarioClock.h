    // ==========================================
    // Create a 64x64 off-screen canvas
    // ==========================================
    GFXcanvas16 clockCanvas(64, 64);

    // --- Font Helper ---
    bool getGlyphInfo(char c, uint8_t &offset, uint8_t &width, uint8_t &x_offset) {
        switch(c) {
            case '0': offset = 64;  width = 7; x_offset = 0; return true;
            case '1': offset = 71;  width = 5; x_offset = 1; return true;
            case '2': offset = 76;  width = 7; x_offset = 0; return true;
            case '3': offset = 83;  width = 7; x_offset = 0; return true;
            case '4': offset = 90;  width = 7; x_offset = 0; return true;
            case '5': offset = 97;  width = 7; x_offset = 0; return true;
            case '6': offset = 104; width = 7; x_offset = 0; return true;
            case '7': offset = 111; width = 7; x_offset = 0; return true;
            case '8': offset = 118; width = 7; x_offset = 0; return true;
            case '9': offset = 125; width = 7; x_offset = 0; return true;
            case '?': offset = 150; width = 7; x_offset = 0; return true;
            default: return false;
        }
    }

    void drawMarioText(String text, int x, int y, uint16_t color) {
        int cursorX = x;
        for (int i = 0; i < text.length(); i++) {
            char c = text.charAt(i);
            uint8_t offset, width, x_offset_char;
            
            if (!getGlyphInfo(c, offset, width, x_offset_char)) {
                cursorX += 8; 
                continue;
            }

            int height = 7;
            int y_offset = -6;
            int x_advance = 8;

            for (int row = 0; row < height; row++) {
                int destY = y + y_offset + row;
                int rowStart = row * width;
                
                for (int col = 0; col < width; col++) {
                    int destX = cursorX + x_offset_char + col;
                    int bitIndex = rowStart + col;
                    
                    int byteIndex = offset + (bitIndex / 8);
                    int bitShift = 7 - (bitIndex % 8);
                    
                    if ((FONT_BITMAPS[byteIndex] >> bitShift) & 1) {
                        clockCanvas.drawPixel(destX, destY, color);
                    }
                }
            }
            cursorX += x_advance;
        }
    }

    void drawSprite(int x, int y, int width, int height, const uint16_t *data) {
        for (int i = 0; i < width * height; i++) {
            uint16_t color = data[i];
            if (color != _MASK) {
                int px = x + (i % width);
                int py = y + (i / width);
                clockCanvas.drawPixel(px, py, color);
            }
        }
    }

    void drawClouds(int x, int y) {
        clockCanvas.fillRect(x + 4, y, 16, 8, M_WHITE);
        clockCanvas.fillRect(x + 2, y + 2, 20, 6, M_WHITE);
        clockCanvas.fillRect(x, y + 4, 24, 4, M_WHITE);
    }

// --- Main Update and Render Loop ---
    void drawClockFrame(int hours, int minutes) {
        unsigned long now = millis();

        // 1. Check for minute changes
        if (lastMinute != -1 && lastMinute != minutes) {
            if (!mario_isJumping) {
                mario_isJumping = true;
                mario_up = true;
                mario_y = 40;
            }
        }
        lastMinute = minutes;

        // 2. ONLY render and calculate math every 50ms (20 FPS)
        if (now - lastFrameTime > 50) {
            
            // --- Update Animations ---
            cloud1_x -= 1; if (cloud1_x < -24) cloud1_x = 64;
            cloud2_x -= 1; if (cloud2_x < -24) cloud2_x = 64;

            if (mario_isJumping) {
                mario_y += (mario_up ? -3 : 3);
                if (mario_up && mario_y <= 26) {
                    mario_up = false;
                    hourBlock_isHit = true; hourBlock_up = true;
                    minBlock_isHit = true;  minBlock_up = true;
                }
                if (!mario_up && mario_y >= 40) {
                    mario_isJumping = false;
                    mario_y = 40;
                }
            }

            if (hourBlock_isHit) {
                hourBlock_offset += (hourBlock_up ? -2 : 2);
                if (hourBlock_up && hourBlock_offset <= -4) hourBlock_up = false;
                if (!hourBlock_up && hourBlock_offset >= 0) {
                    hourBlock_offset = 0; hourBlock_isHit = false;
                }
            }
            
            if (minBlock_isHit) {
                minBlock_offset += (minBlock_up ? -2 : 2);
                if (minBlock_up && minBlock_offset <= -4) minBlock_up = false;
                if (!minBlock_up && minBlock_offset >= 0) {
                    minBlock_offset = 0; minBlock_isHit = false;
                }
            }

            // --- Render the Canvas ---
            clockCanvas.fillScreen(SKY_COLOR);

            drawClouds(cloud1_x, cloud1_y);
            drawClouds(cloud2_x, cloud2_y);
            
            for (int gx = 0; gx < 64; gx += 8) {
                drawSprite(gx, 56, 8, 8, GROUND);
            }

            drawSprite(43, 47, 21, 9, BUSH);
            drawSprite(hourBlock_x, hourBlock_startY + hourBlock_offset, 19, 19, BLOCK);
            drawSprite(minBlock_x, minBlock_startY + minBlock_offset, 19, 19, BLOCK);
            
            String hh = (hours < 10 ? "0" : "") + String(hours);
            String mm = (minutes < 10 ? "0" : "") + String(minutes);
            drawMarioText(hh, hourBlock_x + 2, hourBlock_startY + hourBlock_offset + 12, M_BLACK);
            drawMarioText(mm, minBlock_x + 2, minBlock_startY + minBlock_offset + 12, M_BLACK);

            if (mario_isJumping) {
                drawSprite(mario_x, mario_y, 17, 16, MARIO_JUMP);
            } else {
                drawSprite(mario_x, mario_y, 13, 16, MARIO_IDLE);
            }

            // --- Apply Night Vision ---
            if (currentIsNight) {
                uint16_t* buf = clockCanvas.getBuffer();
                for (int i = 0; i < 64 * 64; i++) {
                    buf[i] = applyNightVision(buf[i]);
                }
            }
            
            // --- Centered Offset Calculation ---
            int matrixW = dma_display->width();
            int matrixH = dma_display->height();
            int offsetX = (matrixW - 64) / 2;
            int offsetY = (matrixH - 64) / 2;
            if (offsetX < 0) offsetX = 0;
            if (offsetY < 0) offsetY = 0;

            // Clear surrounding borders if panel size is larger than 64x64
            if (matrixW > 64 || matrixH > 64) {
                dma_display->fillScreen(0);
            }

            // --- Push Centered to Matrix ---
            dma_display->drawRGBBitmap(offsetX, offsetY, clockCanvas.getBuffer(), 64, 64);

            lastFrameTime = now;
        }
    }
