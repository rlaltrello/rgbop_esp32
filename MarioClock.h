    int hourBlock_y = 8;
    int hourBlock_startY = 8;
    int hourBlock_offset = 0;
    bool hourBlock_isHit = false;
    bool hourBlock_up = true;

    int minBlock_x = 32;
    int minBlock_y = 8;
    int minBlock_startY = 8;
    int minBlock_offset = 0;
    bool minBlock_isHit = false;
    bool minBlock_up = true;

