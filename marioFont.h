// Custom C++ Class to mimic your Font wrapper
class CustomMarioFont {
public:
    template <typename CtxType>
    // --- Added scale parameter defaulting to 1 ---
    void drawText(CtxType* ctx, const std::string& text, int startX, int startY, int scale = 1) {
        int currentX = startX;
        
        for (char c : text) {
            int charCode = (int)c;
            
            // Skip characters outside our map
            if (charCode < 32 || charCode > 126) continue;
            
            const MarioGlyph& glyph = MarioFontMetrics[charCode - 32];
            int bitIndex = 0;
            
            for (int y = 0; y < glyph.h; y++) {
                for (int x = 0; x < glyph.w; x++) {
                    int byteIndex = glyph.offset + (bitIndex / 8);
                    int bitNumber = 7 - (bitIndex % 8);
                    
                    bool isOn = (MarioFontBitmaps[byteIndex] & (1 << bitNumber)) != 0;
                    
                    if (isOn) {
                        // Apply scale to X, Y, Width, and Height
                        int drawX = currentX + (glyph.xOff * scale) + (x * scale);
                        int drawY = startY + (glyph.yOff * scale) + (y * scale);
                        ctx->fillRect(drawX, drawY, scale, scale);
                    }
                    bitIndex++;
                }
            }
            // Apply scale to the advance so letters space out properly
            currentX += (glyph.adv * scale);
        }
    }

    // --- Added scale parameter defaulting to 1 ---
    int getTextWidth(const std::string& text, int scale = 1) {
        int totalWidth = 0;
        for (char c : text) {
            int charCode = (int)c;
            if (charCode >= 32 && charCode <= 126) {
                totalWidth += (MarioFontMetrics[charCode - 32].adv * scale);
            }
        }
        return totalWidth;
    }
};